#lista de cidades
cidades = ["Rio de Janeiro", "São Luís", "Goiânia", "Brasília", "Fortaleza"]

#Ordena a lista
cidades.sort()
# Exibe a lista em ordem alfabetica
for cidade in cidades:
    print(cidade)

# Reverter a lista
cidade.sort(reverse=True)

# exibe a lista em ordem reversa
for cidade in cidades:
    print(cidade)